#!/bin/bash
# 编译脚本 - 3D IC 全局布线器

echo "========================================================================"
echo "编译 3D IC 全局布线器"
echo "========================================================================"

# 检查编译器
if ! command -v g++ &> /dev/null; then
    echo "错误: 未找到 g++ 编译器"
    echo "安装方法: sudo apt-get install g++"
    exit 1
fi

echo "编译器版本:"
g++ --version | head -1

echo ""
echo "开始编译..."

# 编译参数
CXX=g++
CXXFLAGS="-std=c++17 -O3 -Wall -Wextra"
SRC=src/router.cpp
OUT=router

# 编译
$CXX $CXXFLAGS -o $OUT $SRC

if [ $? -eq 0 ]; then
    echo ""
    echo "========================================================================"
    echo "编译成功！"
    echo "========================================================================"
    echo ""
    echo "可执行文件: $OUT"
    ls -lh $OUT
    echo ""
    echo "测试运行:"
    ./$OUT --help
    echo ""
    echo "========================================================================"
else
    echo ""
    echo "========================================================================"
    echo "编译失败！"
    echo "========================================================================"
    exit 1
fi
