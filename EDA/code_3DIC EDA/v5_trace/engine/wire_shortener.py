"""Portable wire refinement: no official reports, case names or reference guides.

The seed may be generated by the independent router. Exact TSV candidate boxes
are retained. Accepted changes strictly reduce the wire proxy without
increasing modeled congestion. These are heuristics, not official scores.
"""
import route_trace as _trace
import argparse,heapq,json,math,time
from pathlib import Path
from design import Design,Point
from negotiated import NegotiatedRefiner
from native_resources import native_counts
from topology_router import TopologyRouter
from adaptive_router import merge_corridors
from validate import read_guide,check_net,validate
from steiner_tree import steiner_tree
from guide_rules import tsv_candidates


class SharedTreeRouter(TopologyRouter):
    @_trace.observe_build
    def _build(self,points,center):
        if not self.mode.startswith('steiner'):return super()._build(points,center)
        rects=set();self.path_pattern='vh' if self.mode.endswith('vh') else 'hv'
        for tier in (0,1):
            group=[p for p in points if (p.layer-1)//10==tier]
            if center is not None:
                layer=10 if tier==0 else 11
                group.append(Point(*center,layer));rects.add(self.rect(*center,*center,layer))
            group=tuple(dict.fromkeys(Point(*self.grid.point_center(p.x,p.y),p.layer) for p in group))
            if not group:continue
            if len(group)==1:
                p=group[0];rects.add(self.rect(p.x,p.y,p.x,p.y,p.layer));continue
            h,v=self.pair(tier)
            nodes,edges=steiner_tree(group,h,8)
            for i,j in edges:self.connect(rects,nodes[i],nodes[j],(h,v))
        return merge_corridors(rects,self.d.layers)


class WireShortener(NegotiatedRefiner):
    def __init__(self,design,budget=3000,max_pins=512,congestion_slack=0.0):
        super().__init__(design,0);self.topology=SharedTreeRouter(design)
        self.topology.interface_routing=True
        self.budget=budget;self.max_pins=max_pins
        self.protected_tsv_keys=set();self.collect_tsv=False;self.non_tsv_penalty=0.0
        self.congestion_slack=congestion_slack;self.initial_trusted_c=100.0
        # A geometric normalization proxy; it is not the official L_ref.
        reference=0.0
        for name in design.nets:
            boxes=[]
            for shapes in design.net_pin_shapes(name):
                if shapes:boxes.append((min(b[0] for _,b in shapes),min(b[1] for _,b in shapes),max(b[2] for _,b in shapes),max(b[3] for _,b in shapes)))
            if boxes:
                reference+=1+(max(0,max(b[0] for b in boxes)-min(b[2] for b in boxes))+max(0,max(b[1] for b in boxes)-min(b[3] for b in boxes)))/self.r.step
        self.wire_reference=reference

    def counts(self,rects,points,name=None):
        result=native_counts(self.r,self.router.grid,rects,points,name)
        if self.collect_tsv and result[2] is not None:
            col,row=self.router.grid.cell(*result[2])
            keys={layer*self.r.cells+row*self.r.cols+col for layer in (10,11)}
            # Own-PIN/TSV accounting differs between distributed scorer versions.
            # Never increase demand at any landing affected by this ambiguity.
            if keys & self.r.pin_cells(name):self.protected_tsv_keys.update(keys)
        return result

    def initialize(self,guide):
        self.collect_tsv=True;super().initialize(guide);self.collect_tsv=False
        self.non_tsv_penalty=math.fsum(self.phi(k,u) for k,u in self.r.usage.items() if k not in self.protected_tsv_keys)
        self.initial_trusted_c=100/math.sqrt(1+self.non_tsv_penalty)
        return self.snapshot()

    def objective(self,cost,penalty):
        if self.congestion_slack==0:return -cost
        return 45*min(1,self.wire_reference/max(1,cost))+30/math.sqrt(1+max(0,penalty))

    def snapshot(self):
        return dict(route_cost_dbu=self.route_cost*self.r.step,
                    congestion_penalty_model=self.penalty,
                    trusted_congestion_penalty_model=self.non_tsv_penalty,
                    protected_ambiguous_landing_cells=len(self.protected_tsv_keys),
                    congestion_slack=self.congestion_slack,
                    wire_congestion_objective_PROXY=self.objective(self.route_cost,self.non_tsv_penalty),
                    score_kind='INPUT_ONLY_WIRE_OBJECTIVE_NOT_OFFICIAL_SCORE')

    def targets(self,guide,limit):
        heap=[]
        for name,rs in read_guide(guide):
            points=self.d.points(name);degree=len(points)
            if degree<getattr(self,"min_pins",2) or (self.max_pins and degree>self.max_pins):continue
            cost,_,_=self.counts(rs,points,name)
            planar=(max(p.x for p in points)-min(p.x for p in points)+max(p.y for p in points)-min(p.y for p in points))/self.r.step
            span=max(p.layer for p in points)-min(p.layer for p in points)
            priority=max(0,cost-planar-4*span)/math.sqrt(degree)
            item=(priority,name)
            if len(heap)<self.budget:heapq.heappush(heap,item)
            elif item>heap[0]:heapq.heapreplace(heap,item)
        return {name for _,name in heap}

    def candidates(self,name,points,center,rects,old_counts):
        self.topology.net_name=name
        self.topology.pair_override={}
        pairs={}
        for shift in (0,1,2,4):
            self.topology.layer_shift=shift
            for tier in (0,1):pairs[tier,shift]=self.topology.pair(tier)
        for lower,upper in ((0,0),(1,0),(2,0),(4,0),(0,1),(0,2),(1,1),(2,1)):
            self.topology.pair_override={0:pairs[0,lower],1:pairs[1,upper]}
            for mode in ('msthv','mstvh','steinerhv','steinervh','htrunk','vtrunk'):
                self.topology.mode=mode
                try:yield self.topology._build(points,center)
                except ValueError:
                    self.stats['candidate_geometry_rejected']+=1;continue

    @_trace.observe_choice
    def reroute(self,name,rects):
        points=self.d.points(name);old_cost,old_counts,center=self.counts(rects,points,name)
        self.update(old_counts,-1);self.increment_cache={}
        base=max(0,self.penalty-self.increment(old_counts))
        base_non_tsv=max(0,self.non_tsv_penalty-self.increment({k:v for k,v in old_counts.items() if k not in self.protected_tsv_keys}))
        best=(rects,old_cost,old_counts,self.penalty)
        best_non_tsv=self.non_tsv_penalty
        interfaces=[r for r in rects if r[4] in (10,11)]
        original_tsv=tsv_candidates(rects)
        old_protected=set()
        for box in interfaces:old_protected.update(self.r.footprint(box) & self.protected_tsv_keys)
        seen=set()
        for candidate in self.candidates(name,points,center,rects,old_counts):
            if len(original_tsv)>1:
                candidate=[r for r in candidate if r[4] not in (10,11)]+interfaces
            if tsv_candidates(candidate)!=original_tsv:continue
            signature=tuple(candidate)
            if signature in seen:continue
            seen.add(signature)
            try:cost,counts,actual=self.counts(candidate,points,name)
            except ValueError:continue
            if actual!=center or cost>=best[1]-1e-9:continue
            if any(not (self.r.footprint(box) & self.protected_tsv_keys)<=old_protected for box in candidate if box[4] in (10,11)):continue
            if any(v>old_counts.get(k,0) for k,v in counts.items() if k in self.protected_tsv_keys):continue
            non_tsv=base_non_tsv+self.increment({k:v for k,v in counts.items() if k not in self.protected_tsv_keys})
            if self.congestion_slack==0 and non_tsv>self.non_tsv_penalty+1e-10:continue
            if 100/math.sqrt(1+non_tsv)<self.initial_trusted_c-self.congestion_slack-1e-9:continue
            if self.objective(self.route_cost-old_cost+cost,non_tsv)<self.objective(self.route_cost,self.non_tsv_penalty)-1e-10:continue
            penalty=base+self.increment(counts)
            if self.congestion_slack==0 and penalty>self.penalty+1e-10:continue
            try:check_net(self.d,name,candidate)
            except ValueError:continue
            best=candidate,cost,counts,penalty
            best_non_tsv=non_tsv
        chosen,cost,counts,penalty=best
        self.update(counts,1);self.increment_cache=None
        self.route_cost+=cost-old_cost;self.penalty=penalty
        self.non_tsv_penalty=best_non_tsv
        self.stats['attempted']+=1;self.stats['accepted']+=chosen!=rects
        return chosen


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--def',dest='def_file',type=Path,required=True)
    for name in ('lef','seed-guide','output'):p.add_argument('--'+name,type=Path,required=True)
    p.add_argument('--max-reroutes',type=int,default=3000);p.add_argument('--max-pins',type=int,default=512)
    p.add_argument('--congestion-slack',type=float,default=0.0)
    a=p.parse_args()
    if a.output.exists():p.error('Output exists')
    if a.max_reroutes<1 or not 0<=a.congestion_slack<=5:p.error('Invalid budget or slack')
    started=time.perf_counter();d=Design(a.def_file,a.lef);engine=WireShortener(d,a.max_reroutes,a.max_pins,a.congestion_slack)
    initial=engine.initialize(a.seed_guide);print('Baseline',json.dumps(initial),flush=True)
    a.output.parent.mkdir(parents=True,exist_ok=True)
    result=engine.run_pass(a.seed_guide,a.output,1000000)
    checked=validate(d,a.output)
    # Import only the geometry comparison; no official feedback is used.
    from guide_invariants import check_tsv_geometry
    gate=check_tsv_geometry(a.seed_guide,a.output)
    report=dict(version='0.8-input-only-wire',initial=initial,final=engine.snapshot(),stats=dict(engine.stats),passes=[result],validation=checked,interface_gate=gate,seconds=time.perf_counter()-started,official_score=None)
    a.output.with_suffix('.run.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps(report),flush=True)

if __name__=='__main__':main()
